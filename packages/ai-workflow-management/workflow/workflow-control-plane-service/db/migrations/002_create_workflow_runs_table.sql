CREATE COLUMN TABLE "AIW_WORKFLOW_RUNS" (
    "ID"                NVARCHAR(64)   NOT NULL PRIMARY KEY,
    "WORKFLOW_ID"       NVARCHAR(64)   NOT NULL,
    "WORKFLOW_VERSION"  NVARCHAR(32)   NOT NULL,
    "INPUT_DATA"        NCLOB,
    "OUTPUT_DATA"       NCLOB,
    "STATUS"            NVARCHAR(32)   NOT NULL DEFAULT 'PENDING',
    "CONTEXT"           NCLOB,
    "STARTED_AT"        NVARCHAR(64),
    "COMPLETED_AT"      NVARCHAR(64),
    "ERROR"             NCLOB,
    "CORRELATION_ID"    NVARCHAR(128),
    "CALLBACK_TOPIC"    NVARCHAR(256)
);

CREATE INDEX "IDX_AIW_RUNS_WORKFLOW" ON "AIW_WORKFLOW_RUNS" ("WORKFLOW_ID");

CREATE INDEX "IDX_AIW_RUNS_STATUS" ON "AIW_WORKFLOW_RUNS" ("STATUS");