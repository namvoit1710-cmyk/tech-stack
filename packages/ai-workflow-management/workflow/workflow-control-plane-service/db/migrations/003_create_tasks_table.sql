CREATE COLUMN TABLE "AIW_TASKS" (
    "ID"              NVARCHAR(128)  NOT NULL PRIMARY KEY,
    "RUN_ID"          NVARCHAR(64)   NOT NULL,
    "NODE_ID"         NVARCHAR(128)  NOT NULL,
    "STATUS"          NVARCHAR(32)   NOT NULL DEFAULT 'PENDING',
    "INPUT_REFS"      NCLOB,
    "OUTPUT_REF"      NCLOB,
    "RETRY_COUNT"     INTEGER        NOT NULL DEFAULT 0,
    "STARTED_AT"      NVARCHAR(64),
    "COMPLETED_AT"    NVARCHAR(64),
    "ERROR"           NCLOB,
    "WORKER_ID"       NVARCHAR(128)
);

CREATE INDEX "IDX_AIW_TASKS_RUN" ON "AIW_TASKS" ("RUN_ID");

CREATE INDEX "IDX_AIW_TASKS_STATUS" ON "AIW_TASKS" ("RUN_ID", "STATUS");
